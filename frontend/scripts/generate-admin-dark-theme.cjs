// Generates src/modules/admin/styles/adminDarkTheme.generated.css, the
// repetitive part of the admin dark theme: per-hue tints at every opacity
// step, neutral opacity variants, and the light/dark arbitrary hex classes
// actually used in the admin code (scanned from src/modules/admin).
//
// Run from frontend/ after adding new colours to admin pages:
//   node scripts/generate-admin-dark-theme.cjs
const fs = require('fs');
const path = require('path');

const D = "html[data-admin-theme='dark'] .redigo-admin-root";
const ADMIN_DIR = path.join(__dirname, '..', 'src', 'modules', 'admin');
const OUTPUT = path.join(ADMIN_DIR, 'styles', 'adminDarkTheme.generated.css');

const HUES = {
  red: ['239,68,68', '#f87171'],
  rose: ['244,63,94', '#fb7185'],
  orange: ['249,115,22', '#fb923c'],
  amber: ['245,158,11', '#fbbf24'],
  yellow: ['234,179,8', '#facc15'],
  lime: ['132,204,22', '#a3e635'],
  green: ['34,197,94', '#4ade80'],
  emerald: ['16,185,129', '#34d399'],
  teal: ['20,184,166', '#2dd4bf'],
  cyan: ['6,182,212', '#67e8f9'],
  sky: ['14,165,233', '#7dd3fc'],
  blue: ['59,130,246', '#93c5fd'],
  indigo: ['99,102,241', '#a5b4fc'],
  violet: ['139,92,246', '#c4b5fd'],
  purple: ['168,85,247', '#d8b4fe'],
  fuchsia: ['217,70,239', '#f0abfc'],
  pink: ['236,72,153', '#f9a8d4'],
};
const ALPHAS = ['', '/10', '/20', '/30', '/40', '/50', '/60', '/70', '/80', '/90'];

const out = [];
const rule = (selectors, body) => out.push(`${selectors.map((s) => `${D} ${s}`).join(',\n')} {\n  ${body}\n}`);
const cls = (name) => `.${name.replace(/([:/\[\]#.])/g, '\\$1')}`;
const withHover = (name) => [cls(name), `${cls(`hover:${name}`)}:hover`];

out.push('/* Pale hue tints at every opacity step become a translucent wash. */');
for (const [hue, [rgb, light]] of Object.entries(HUES)) {
  rule(ALPHAS.flatMap((alpha) => withHover(`bg-${hue}-50${alpha}`)), `background-color: rgba(${rgb}, 0.12) !important;`);
  rule(
    ['100', '200'].flatMap((shade) => ALPHAS.flatMap((alpha) => withHover(`bg-${hue}-${shade}${alpha}`))),
    `background-color: rgba(${rgb}, 0.2) !important;`,
  );
  rule(
    ['500', '600', '650', '700', '800', '900', '950'].flatMap((shade) => [
      ...withHover(`text-${hue}-${shade}`),
      `.group:hover ${cls(`group-hover:text-${hue}-${shade}`)}`,
    ]),
    `color: ${light} !important;`,
  );
  rule(
    ['50', '100', '200', '300'].flatMap((shade) => ALPHAS.flatMap((alpha) => withHover(`border-${hue}-${shade}${alpha}`))),
    `border-color: rgba(${rgb}, 0.32) !important;`,
  );
}

out.push('/* Neutral greys with an opacity suffix (bg-gray-200/50 ...). */');
rule(
  ['gray', 'slate'].flatMap((n) => ['50', '100', '200', '300'].flatMap((shade) => ALPHAS.filter(Boolean).flatMap((alpha) => withHover(`bg-${n}-${shade}${alpha}`)))),
  'background-color: var(--d-raised) !important;',
);

// Arbitrary hex classes found in the admin sources.
const walk = (dir) => fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
  const full = path.join(dir, entry.name);
  return entry.isDirectory() ? walk(full) : /\.(jsx?|tsx?)$/.test(entry.name) ? [full] : [];
});
const found = new Set();
for (const file of walk(ADMIN_DIR)) {
  for (const match of fs.readFileSync(file, 'utf8').matchAll(/\b(bg|border|text)-\[#([0-9a-fA-F]{6})\]/g)) found.add(`${match[1]}|${match[2]}`);
}
const luminance = (hex) => {
  const [r, g, b] = [0, 2, 4].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255).map((v) => (v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
const lightBg = [];
const lightBorder = [];
const darkText = [];
for (const key of [...found].sort()) {
  const [kind, hex] = key.split('|');
  const l = luminance(hex);
  if (kind === 'bg' && l > 0.72) lightBg.push(`bg-[#${hex}]`);
  if (kind === 'border' && l > 0.72) lightBorder.push(`border-[#${hex}]`);
  if (kind === 'text' && l < 0.06) darkText.push(`text-[#${hex}]`);
}
out.push('/* Light arbitrary backgrounds, borders and dark arbitrary text used in the admin code. */');
if (lightBg.length) rule(lightBg.flatMap(withHover), 'background-color: var(--d-raised) !important;');
if (lightBorder.length) rule(lightBorder.map(cls), 'border-color: var(--d-border) !important;');
if (darkText.length) rule(darkText.map(cls), 'color: var(--d-text) !important;');

const header = '/* Generated by scripts/generate-admin-dark-theme.cjs. Do not edit by hand. */';
fs.writeFileSync(OUTPUT, `${header}\n\n${out.join('\n\n')}\n`);
console.log(`wrote ${path.relative(process.cwd(), OUTPUT)}`);
